// Integration tests: they talk to a real Postgres.
// They skip when no database is configured, so CI stays green without
// holding the secret.
func testDB(t *testing.T) *sql.DB {
	t.Helper()
	// Missing files are fine: the test skips below without a URL.
	_ = godotenv.Load("../.env.local")
	_ = godotenv.Load("../.env")

	// Only the dedicated test branch: these tests write and delete rows,
	// so they must never fall back to DATABASE_URL, which is dev's or
	// production's.
	dsn := os.Getenv("TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("no TEST_DATABASE_URL — skipping integration test")
	}

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	db, err := NewDatabase(ctx, dsn)
	if err != nil {
		t.Fatalf("connecting: %v", err)
	}
	t.Cleanup(func() { db.Close() })

	if err := Migrate(context.Background(), db); err != nil {
		t.Fatalf("migrating: %v", err)
	}
	return db
}

func TestSchemaIsApplied(t *testing.T) {
	db := testDB(t)
	ctx := context.Background()

	for _, table := range []string{"products", "product_images", "site_state", "admin_users", "sessions"} {
		var exists bool
		err := db.QueryRowContext(ctx,
			`SELECT EXISTS (SELECT 1 FROM information_schema.tables
			 WHERE table_schema = 'public' AND table_name = $1)`, table,
		).Scan(&exists)
		if err != nil {
			t.Fatalf("querying %s: %v", table, err)
		}
		if !exists {
			t.Errorf("table %s is missing", table)
		}
	}
}

func TestProductRoundTripAndUpdatedAtTrigger(t *testing.T) {
	db := testDB(t)
	ctx := context.Background()

	const slug = "integration-test-do-not-use"
	cleanup := func() {
		// Best effort: a leftover row only affects this test's next run.
		_, _ = db.ExecContext(ctx, `DELETE FROM products WHERE slug = $1`, slug)
	}
	cleanup()
	t.Cleanup(cleanup)

	// IDs come from the application, never from the database.
	id := uuid.New().String()
	var updatedAt time.Time
	err := db.QueryRowContext(ctx,
		`INSERT INTO products (id, slug, name, price_cents, sizes, description, details, position)
		 VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
		 RETURNING updated_at`,
		id, slug, "Test Bikini", 18900,
		[]string{"P", "M"}, "description", []string{"one detail"}, 99,
	).Scan(&updatedAt)
	if err != nil {
		t.Fatalf("inserting: %v", err)
	}

	// Read back, confirming the arrays survive the round trip.
	var name string
	var cents int64
	var sizes, details []string
	types := pgtype.NewMap()
	err = db.QueryRowContext(ctx,
		`SELECT name, price_cents, sizes, details FROM products WHERE id = $1`, id,
	).Scan(&name, &cents, types.SQLScanner(&sizes), types.SQLScanner(&details))
	if err != nil {
		t.Fatalf("reading back: %v", err)
	}
	if name != "Test Bikini" {
		t.Errorf("name = %q", name)
	}
	if cents != 18900 {
		t.Errorf("price_cents = %d, want 18900", cents)
	}
	if len(sizes) != 2 || sizes[0] != "P" {
		t.Errorf("sizes = %v", sizes)
	}
	if len(details) != 1 {
		t.Errorf("details = %v", details)
	}

	// The trigger must bump updated_at without anyone writing the column.
	// Each Exec is its own transaction, and now() is the transaction start
	// time — which is why updated_at moves here and would not inside a
	// single transaction.
	time.Sleep(50 * time.Millisecond)
	if _, err := db.ExecContext(ctx,
		`UPDATE products SET price_cents = 19900 WHERE id = $1`, id); err != nil {
		t.Fatalf("updating: %v", err)
	}

	var newUpdatedAt time.Time
	if err := db.QueryRowContext(ctx,
		`SELECT updated_at FROM products WHERE id = $1`, id).Scan(&newUpdatedAt); err != nil {
		t.Fatalf("re-reading: %v", err)
	}
	if !newUpdatedAt.After(updatedAt) {
		t.Errorf("trigger did not bump updated_at: before %v, after %v", updatedAt, newUpdatedAt)
	}
}

func TestSiteStateIsSingleRow(t *testing.T) {
	db := testDB(t)
	ctx := context.Background()

	var count int
	if err := db.QueryRowContext(ctx, `SELECT count(*) FROM site_state`).Scan(&count); err != nil {
		t.Fatalf("counting: %v", err)
	}
	if count != 1 {
		t.Fatalf("site_state has %d rows, want 1", count)
	}

	// The boolean primary key with a CHECK must reject a second row.
	if _, err := db.ExecContext(ctx, `INSERT INTO site_state (id) VALUES (FALSE)`); err == nil {
		// Best effort undo; the test already fails either way.
		_, _ = db.ExecContext(ctx, `DELETE FROM site_state WHERE id = FALSE`)
		t.Error("a second site_state row was accepted; it should be rejected")
	}
}

// IDs are UUIDs generated by the application, so they cannot be guessed by
// counting. A default on the column would let a sequence sneak back in.
func TestIDsAreUUIDsWithoutDefault(t *testing.T) {
	db := testDB(t)
	ctx := context.Background()

	tests := []struct{ table, column string }{
		{"products", "id"},
		{"product_images", "id"},
		{"product_images", "product_id"},
		{"admin_users", "id"},
	}

	for _, tt := range tests {
		t.Run(tt.table+"."+tt.column, func(t *testing.T) {
			var dataType string
			var columnDefault sql.NullString
			err := db.QueryRowContext(ctx,
				`SELECT data_type, column_default FROM information_schema.columns
				 WHERE table_schema = 'public' AND table_name = $1 AND column_name = $2`,
				tt.table, tt.column,
			).Scan(&dataType, &columnDefault)
			if err != nil {
				t.Fatalf("querying column: %v", err)
			}
			if dataType != "uuid" {
				t.Errorf("type = %q, want uuid", dataType)
			}
			if columnDefault.Valid {
				t.Errorf("default = %q, want none", columnDefault.String)
			}
		})
	}
}
