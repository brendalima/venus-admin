package storage

import (
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
)

var _ ImageStore = (*Disk)(nil)

const immutableCacheControl = "public, max-age=31536000, immutable"

// Disk keeps the photo files in a local directory. It is for development
// only, so the whole photo flow works without R2 credentials; cmd/api
// serves the directory under /media.
type Disk struct {
	dir string
}

func NewDisk(dir string) (*Disk, error) {
	if dir == "" {
		return nil, errors.New("missing media directory")
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("couldn't create media directory: %w", err)
	}
	return &Disk{dir: dir}, nil
}

func MustNewDisk(dir string) *Disk {
	d, err := NewDisk(dir)
	if err != nil {
		panic(fmt.Errorf("couldn't create disk store: %w", err))
	}
	return d
}

func (d *Disk) Put(_ context.Context, key string, data []byte, _ string) error {
	path, err := d.path(key)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("couldn't create directory for %s: %w", key, err)
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return fmt.Errorf("couldn't write %s: %w", key, err)
	}
	return nil
}

// Delete succeeds for a key that is already gone, like R2.
func (d *Disk) Delete(_ context.Context, key string) error {
	path, err := d.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("couldn't delete %s: %w", key, err)
	}
	return nil
}

// path keeps keys inside the directory. Keys are generated by the service,
// but a store that writes files should not depend on that.
func (d *Disk) path(key string) (string, error) {
	if !filepath.IsLocal(key) {
		return "", fmt.Errorf("invalid key %q", key)
	}
	return filepath.Join(d.dir, filepath.FromSlash(key)), nil
}
